const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const path = require('node:path');
const html = fs.readFileSync(path.join(__dirname, '../demos/recruitment/index.html'), 'utf8');
const script = html.match(/<script>([\s\S]*?)<\/script>/)[1];
function setup(saved, blocked=false) {
  const nodes = new Map();
  let open = false;
  const alerts = [];
  const node = id => {
    if (!nodes.has(id)) nodes.set(id, {value:'',checked:false,innerHTML:'',showModal(){open=true},close(){open=false}});
    return nodes.get(id);
  };
  const context = vm.createContext({structuredClone, console, document:{getElementById:node,querySelectorAll:()=>[]},localStorage:{getItem(){if(blocked)throw Error('blocked');return saved??null},setItem(k,v){if(blocked)throw Error('quota');saved=v}},alert:m=>alerts.push(m),confirm:()=>true});
  vm.runInContext(script,context);
  const run = code=>vm.runInContext(code,context);
  const fill = values=>Object.entries(values).forEach(([k,v])=>node(k).value=String(v));
  return {run,node,fill,alerts,get open(){return open},get saved(){return saved}};
}
