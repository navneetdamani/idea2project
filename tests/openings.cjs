const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const path = require('node:path');
const source = fs.readFileSync(path.join(__dirname, '../applications/recruitment/openings.js'), 'utf8');
const cards = {innerHTML: ''};
const count = {textContent: ''};
const listeners = {};
const search = {value: '', focus() { this.focused = true; }, addEventListener(name, callback) { listeners[name] = callback; }};
const clear = {disabled: true, addEventListener(name, callback) { listeners.clear = callback; }};
const form = {addEventListener() {}};
const elements = {'current-opening-cards': cards, 'opening-result-count': count, 'opening-search': search, 'opening-clear': clear, 'opening-search-form': form};
const context = vm.createContext({document: {getElementById: id => elements[id] || null}, encodeURIComponent});
vm.runInContext(source, context);
assert.equal((cards.innerHTML.match(/<article /g) || []).length, 15);
assert.equal((cards.innerHTML.match(/href="candidate.html\?job=I2P-/g) || []).length, 15);
assert.doesNotMatch(cards.innerHTML, /mailto:|Enquire by email|deloitte|DLTJP|INR|bill rate|zoom\.us|Process Mining/i);
assert.match(count.textContent, /15 openings shown of 15/);
const ids = Array.from(context.TalentFlowOpenings, job => job.id);
assert.deepEqual(ids.slice(0, 5), ['I2P-20261124-01','I2P-20261124-02','I2P-20261124-03','I2P-20261124-04','I2P-20261124-05']);
assert.deepEqual(ids.slice(5, 8), ['I2P-20261118-01','I2P-20261118-02','I2P-20261117-01']);
assert.ok(ids.indexOf('I2P-20261113-01') < ids.indexOf('I2P-20261112-01'));
vm.runInContext("renderCurrentOpenings('  MuLeSoFt CloudHub  ')", context);
assert.equal((cards.innerHTML.match(/<article /g) || []).length, 1);
assert.match(cards.innerHTML, /I2P-20261111-01/);
assert.match(count.textContent, /1 opening shown of 15/);
vm.runInContext("renderCurrentOpenings('sap upgrade')", context);
assert.equal((cards.innerHTML.match(/<article /g) || []).length, 2);
assert.match(cards.innerHTML, /I2P-20261124-04/);
assert.match(cards.innerHTML, /I2P-20261124-05/);
vm.runInContext("renderCurrentOpenings('Hyderabad upgrade')", context);
assert.equal((cards.innerHTML.match(/<article /g) || []).length, 2);
vm.runInContext("renderCurrentOpenings('no-such-opportunity')", context);
assert.match(cards.innerHTML, /No matching openings/);
assert.match(count.textContent, /0 openings shown of 15/);
search.value = 'MuLeSoFt';
listeners.input({target: search});
assert.equal(clear.disabled, false);
listeners.clear();
assert.equal(search.value, '');
assert.equal(search.focused, true);
assert.equal(clear.disabled, true);
assert.equal((cards.innerHTML.match(/<article /g) || []).length, 15);
const title = context.TalentFlowOpenings[0].title;
context.TalentFlowOpenings[0].title = '<img src=x onerror=alert(1)>';
vm.runInContext('renderCurrentOpenings()', context);
assert.doesNotMatch(cards.innerHTML, /<img/);
assert.match(cards.innerHTML, /&lt;img/);
context.TalentFlowOpenings[0].title = title;
assert.doesNotMatch(source, /I2P-20261104-01|I2P-20261106-0[1-6]|I2P-20261103-0[12]|I2P-20261102-0[1-4]|I2P-20261023-0[34]|I2P-20261028-0[1-4]|I2P-20261027-0[1-4]|I2P-20261030-01|I2P-20261112-03/);
assert.doesNotMatch(source, /Boomi Integration Consultant - EDI|strong EDI experience/i);
assert.match(source, /queueing mechanisms/i);
vm.runInContext(source, vm.createContext({document:{getElementById:()=>null},encodeURIComponent}));
console.log('PASS: fifteen openings, date/sequence ordering, multi-term search, clear/no-results behavior, public exclusions and escaping');
